/**
 * Writes public/_redirects so the old Hexo permalinks still land.
 *
 * The blog used to live at /:year/:month/:day/:title/ and now lives at
 * /blog/:slug/. Those old URLs are what search engines and other people's links
 * still point at, so each one is mapped to its post rather than left to 404.
 *
 * Generated from the posts themselves, not written by hand — the date and slug
 * that build the old path are the same ones the post already carries, so the
 * two cannot drift.
 *
 * Netlify merges this file with the redirect rules configured in its UI.
 *
 * Re-run with `pnpm assets:redirects` after adding or renaming a post.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import matter from 'gray-matter';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const postsDir = join(root, 'content', 'posts');
const outFile = join(root, 'public', '_redirects');

const files = (await readdir(postsDir)).filter((f) => f.endsWith('.mdx')).sort();
const rules = [];

for (const file of files) {
  const slug = file.replace(/\.mdx$/, '');
  const { data } = matter(await readFile(join(postsDir, file), 'utf8'));

  // Only posts migrated from Hexo carry a legacyPath. Anything written since
  // never had an old URL, so it gets no redirect — deriving one from the date
  // would publish a rule for a page that never existed.
  if (typeof data.legacyPath !== 'string' || !data.legacyPath) continue;
  rules.push(`${data.legacyPath}  /blog/${slug}/  301`);
}

/**
 * Other GitHub Pages projects that used to live under this domain.
 *
 * While the user site was served by GitHub Pages with indrakusuma.web.id as
 * its custom domain, GitHub served every other repo's Pages site beneath it
 * too — indrakusuma.web.id/thekusuma/ and so on. Moving the domain to Netlify
 * turned those links into this site's 404, and they still get visited.
 *
 * Netlify proxies them (status 200, so the address bar keeps the old URL) to
 * where GitHub now serves them.
 *
 * One rule per project, and no bare-path 301 to add a trailing slash: Netlify
 * matches a rule's path with or without its trailing slash, so
 * `/repo  /repo/  301` also caught `/repo/` itself and redirected it to itself,
 * forever. GitHub Pages adds the slash where a page needs one.
 */
/**
 * The site moved from indrakusuma.web.id to indrakusuma.dev. Both domains point
 * at this Netlify site, which would otherwise serve the same pages twice; these
 * send every request on the old one, path and all, to the new one.
 *
 * They come first and are forced (`!`) so they win over every rule below. An
 * old Hexo permalink on the old domain therefore takes two hops — to the new
 * domain, then to its post — and both are 301s that search engines follow.
 * Keep them for as long as the old domain is renewed: they are what carries its
 * links and rankings across.
 */
const domainRules = ['indrakusuma.web.id', 'www.indrakusuma.web.id'].map(
  (host) => `https://${host}/*  https://indrakusuma.dev/:splat  301!`,
);

const PAGES_PROJECTS = ['thekusuma', 'simple-404-template'];
const projectRules = [
  ...PAGES_PROJECTS.map((repo) => `/${repo}/*  https://idindrakusuma.github.io/${repo}/:splat  200`),
  // The old "about me" page. This site is that page now, so it goes home.
  '/me/*  /  301',
];

const header = [
  '# Generated by scripts/generate-redirects.mjs — do not edit by hand.',
  '',
  '# The previous domain, indrakusuma.web.id, moved to indrakusuma.dev.',
  ...domainRules,
  '',
  '# Old Hexo permalinks (/:year/:month/:day/:title/) from the previous blog.',
  '',
];
const projectHeader = [
  '',
  '# GitHub Pages projects once served under this domain, proxied to where',
  '# GitHub serves them now.',
  '',
];

await writeFile(
  outFile,
  `${header.concat(rules.sort(), projectHeader, projectRules).join('\n')}\n`,
  'utf8',
);
console.log(
  `Wrote ${domainRules.length} domain redirects, ${rules.length} post redirects and ${projectRules.length} project rules to public/_redirects`,
);
