/**
 * Writes public/_redirects so the old Hexo permalinks still land.
 *
 * The blog used to live at /:year/:month/:day/:title/ and now lives at
 * /blog/:slug/. Those old URLs are what search engines and other people's links
 * still point at, so each one is mapped to its post rather than left to 404.
 *
 * Generated from the posts themselves, not written by hand — the date and slug
 * that build the old path are the same ones the post already carries, so the
 * two cannot drift.
 *
 * Netlify merges this file with the redirect rules configured in its UI.
 *
 * Re-run with `pnpm assets:redirects` after adding or renaming a post.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import matter from 'gray-matter';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const postsDir = join(root, 'content', 'posts');
const outFile = join(root, 'public', '_redirects');

const pad = (n) => String(n).padStart(2, '0');

const files = (await readdir(postsDir)).filter((f) => f.endsWith('.mdx')).sort();
const rules = [];

for (const file of files) {
  const slug = file.replace(/\.mdx$/, '');
  const { data } = matter(await readFile(join(postsDir, file), 'utf8'));
  const date = new Date(String(data.date));
  if (Number.isNaN(date.getTime())) throw new Error(`${slug}: unreadable date "${data.date}"`);

  // The old URL used the original filename casing; the new one is lowercase.
  const legacy = typeof data.legacySlug === 'string' ? data.legacySlug : slug;
  const from = `/${date.getFullYear()}/${pad(date.getMonth() + 1)}/${pad(date.getDate())}/${legacy}/`;
  rules.push(`${from}  /blog/${slug}/  301`);
}

const header = [
  '# Generated by scripts/generate-redirects.mjs — do not edit by hand.',
  '# Old Hexo permalinks (/:year/:month/:day/:title/) from the previous blog.',
  '',
];

await writeFile(outFile, `${header.concat(rules.sort()).join('\n')}\n`, 'utf8');
console.log(`Wrote ${rules.length} redirects to public/_redirects`);
